-- The whole schema in one go. It follows legacy/src/lib/server/db/schema.ts table for table, so
-- later slices only add queries, not tables. Deliberate clean-ups against the Drizzle schema are
-- marked "clean-up" below.

CREATE TABLE users (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name text NOT NULL UNIQUE,
	password_hash text NOT NULL,
	created_at timestamptz NOT NULL DEFAULT now(),
	is_admin boolean NOT NULL DEFAULT false,
	-- clean-up: double precision instead of real, so the value round-trips through f64 exactly.
	playback_speed double precision NOT NULL DEFAULT 1.0,
	skip_back integer NOT NULL DEFAULT 30,
	skip_forward integer NOT NULL DEFAULT 15,
	CONSTRAINT playback_speed_range CHECK (playback_speed >= 0.5 AND playback_speed <= 4.0),
	CONSTRAINT skip_back_range CHECK (skip_back > 0 AND skip_back <= 300),
	CONSTRAINT skip_forward_range CHECK (skip_forward > 0 AND skip_forward <= 300)
);

CREATE TABLE auth_tokens (
	value text PRIMARY KEY,
	user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	created_at timestamptz NOT NULL DEFAULT now(),
	last_seen_at timestamptz
);
-- clean-up: revoking "all other tokens" and the user list's last_seen join go by user.
CREATE INDEX auth_token_user ON auth_tokens (user_id);

CREATE TABLE items (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	parent_id integer REFERENCES items (id) ON DELETE CASCADE,
	kind text NOT NULL,
	source_path text UNIQUE,
	title text NOT NULL,
	sort_title text NOT NULL,
	cover_path text,
	artist text,
	album_artist text,
	year integer,
	author text,
	narrator text,
	-- Free text about the item: a podcast's or episode's feed description, or the comment tag of
	-- a book or album. Only ever sent with a single item, never in a list.
	description text,
	series text,
	series_index double precision,
	feed_url text,
	last_checked timestamptz,
	published_at timestamptz,
	added_at timestamptz NOT NULL DEFAULT now(),
	missing_since timestamptz,
	guid text,
	-- Podcasting 2.0 <podcast:chapters url=…>, fetched when the episode is downloaded.
	chapters_url text,
	-- What the feed claims an episode runs for (<itunes:duration>); measured durations live on
	-- tracks, but an episode has none until it is downloaded.
	feed_duration double precision,
	keep_episodes integer,
	-- Fields a person edited by hand; the scanner leaves them alone.
	locked_fields text[] NOT NULL DEFAULT '{}'::text[],
	CONSTRAINT kind_check CHECK (kind IN ('book', 'album', 'podcast', 'episode'))
);
CREATE INDEX item_kind_sort ON items (kind, sort_title);
CREATE INDEX item_series ON items (series) WHERE series IS NOT NULL;
CREATE INDEX item_parent ON items (parent_id) WHERE parent_id IS NOT NULL;
CREATE UNIQUE INDEX item_guid ON items (parent_id, guid) WHERE guid IS NOT NULL;

CREATE TABLE tracks (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	item_id integer NOT NULL REFERENCES items (id) ON DELETE CASCADE,
	position integer NOT NULL,
	path text NOT NULL UNIQUE,
	duration double precision NOT NULL,
	title text,
	disc integer,
	mtime double precision,
	-- clean-up: bigint — a single-file m4b audiobook passes 2 GiB easily.
	size bigint,
	locked_fields text[] NOT NULL DEFAULT '{}'::text[]
);
CREATE UNIQUE INDEX track_item_position ON tracks (item_id, position);

CREATE TABLE chapters (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	item_id integer NOT NULL REFERENCES items (id) ON DELETE CASCADE,
	position integer NOT NULL,
	title text NOT NULL,
	start double precision NOT NULL,
	"end" double precision NOT NULL
);
CREATE UNIQUE INDEX chapter_item_position ON chapters (item_id, position);

CREATE TABLE progress (
	user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	item_id integer NOT NULL REFERENCES items (id) ON DELETE CASCADE,
	position double precision NOT NULL,
	finished boolean NOT NULL DEFAULT false,
	updated_at timestamptz NOT NULL DEFAULT now(),
	PRIMARY KEY (user_id, item_id)
);
-- clean-up: the podcast overview joins progress by episode.
CREATE INDEX progress_item ON progress (item_id);

CREATE TABLE bookmarks (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	item_id integer NOT NULL REFERENCES items (id) ON DELETE CASCADE,
	position double precision NOT NULL,
	title text NOT NULL
);
CREATE UNIQUE INDEX bookmark_user_item_position ON bookmarks (user_id, item_id, position);

CREATE TABLE favorites (
	user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	item_id integer REFERENCES items (id) ON DELETE CASCADE,
	track_id integer REFERENCES tracks (id) ON DELETE CASCADE,
	CONSTRAINT favorite_xor CHECK ((item_id IS NULL) <> (track_id IS NULL))
);
CREATE UNIQUE INDEX favorite_item ON favorites (user_id, item_id) WHERE item_id IS NOT NULL;
CREATE UNIQUE INDEX favorite_track ON favorites (user_id, track_id) WHERE track_id IS NOT NULL;

CREATE TABLE listen_events (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	item_id integer NOT NULL REFERENCES items (id) ON DELETE CASCADE,
	seconds double precision NOT NULL,
	at timestamptz NOT NULL DEFAULT now()
);
-- clean-up: listening stats are always per user over a time range.
CREATE INDEX listen_event_user_at ON listen_events (user_id, at);

CREATE TABLE playback_sessions (
	id text PRIMARY KEY,
	user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	item_id integer NOT NULL REFERENCES items (id) ON DELETE CASCADE,
	started_at timestamptz NOT NULL DEFAULT now(),
	start_position double precision NOT NULL DEFAULT 0,
	closed_at timestamptz
);

CREATE TABLE playlists (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	name text NOT NULL,
	created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX playlist_user ON playlists (user_id);

CREATE TABLE library_config (
	id integer PRIMARY KEY,
	books_dir text,
	music_dir text,
	podcast_keep_episodes integer NOT NULL DEFAULT 0,
	updated_at timestamptz NOT NULL DEFAULT now(),
	CONSTRAINT keep_episodes_range CHECK (podcast_keep_episodes BETWEEN 0 AND 50)
);

CREATE TABLE artist_covers (
	artist text PRIMARY KEY,
	item_id integer REFERENCES items (id) ON DELETE CASCADE,
	image_path text,
	updated_at timestamptz NOT NULL DEFAULT now(),
	CONSTRAINT artist_cover_xor CHECK ((item_id IS NULL) <> (image_path IS NULL))
);

-- Every hand edit, with the value it replaced. One batch id per request, so a bulk change can be
-- undone in one go.
CREATE TABLE metadata_edits (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	batch_id text NOT NULL,
	item_id integer REFERENCES items (id) ON DELETE CASCADE,
	track_id integer REFERENCES tracks (id) ON DELETE CASCADE,
	field text NOT NULL,
	old_value text,
	new_value text,
	user_id integer REFERENCES users (id) ON DELETE SET NULL,
	created_at timestamptz NOT NULL DEFAULT now(),
	CONSTRAINT metadata_edit_target CHECK ((item_id IS NULL) <> (track_id IS NULL))
);
CREATE INDEX metadata_edit_batch ON metadata_edits (batch_id);
CREATE INDEX metadata_edit_item ON metadata_edits (item_id);

CREATE TABLE playlist_entries (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	playlist_id integer NOT NULL REFERENCES playlists (id) ON DELETE CASCADE,
	item_id integer REFERENCES items (id) ON DELETE CASCADE,
	track_id integer REFERENCES tracks (id) ON DELETE CASCADE,
	position integer NOT NULL,
	CONSTRAINT playlist_entry_xor CHECK ((item_id IS NULL) <> (track_id IS NULL))
);
CREATE UNIQUE INDEX playlist_entry_position ON playlist_entries (playlist_id, position);
