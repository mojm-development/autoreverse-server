-- Internet radio stations, one list per user. `source_url` is what was entered or what the
-- directory named (possibly a .m3u/.pls playlist), `stream_url` the address behind it that
-- delivers audio; the server plays that one. A station out of the directory keeps the
-- directory's id, so adding it twice finds the first.
CREATE TABLE radio_stations (
	id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	position integer NOT NULL,
	name text NOT NULL,
	source_url text NOT NULL,
	stream_url text NOT NULL,
	-- What the sender called its stream when it was added; HEAD answers with it without asking.
	content_type text,
	directory_id text,
	homepage text,
	country text,
	tags text[] NOT NULL DEFAULT '{}',
	codec text,
	bitrate integer,
	-- File name under <data>/radio/logos, never a path.
	logo_file text,
	created_at timestamptz NOT NULL DEFAULT now()
);
-- Gapless 1..=n per user, like the entries of a playlist.
CREATE UNIQUE INDEX radio_station_position ON radio_stations (user_id, position);
CREATE UNIQUE INDEX radio_station_stream ON radio_stations (user_id, stream_url);
CREATE UNIQUE INDEX radio_station_directory ON radio_stations (user_id, directory_id)
	WHERE directory_id IS NOT NULL;
